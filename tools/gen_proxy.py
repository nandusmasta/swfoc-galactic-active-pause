"""Generate a forwarding proxy for a system DLL (default: winmm.dll).

Emits:
  src/<name>_proxy.c  - one naked jmp stub per export plus a resolver that loads the
                        real DLL from the system directory
  src/<name>.def      - export table that keeps the original names and ordinals

Usage: python gen_proxy.py [C:\\Windows\\System32\\winmm.dll] [outdir]
"""
import os
import struct
import sys


def read_exports(path):
    d = open(path, "rb").read()
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    optsz = struct.unpack_from("<H", d, pe + 20)[0]
    opt = pe + 24
    secs = []
    for i in range(nsec):
        o = opt + optsz + i * 40
        vs, va, rs, ra = struct.unpack_from("<IIII", d, o + 8)
        secs.append((va, max(vs, rs), ra))

    def off(rva):
        for va, sz, ra in secs:
            if va <= rva < va + sz:
                return rva - va + ra
        raise ValueError(hex(rva))

    exp_rva = struct.unpack_from("<I", d, opt + 112)[0]
    e = off(exp_rva)
    base, nfuncs, nnames, funcs, names, ords = struct.unpack_from("<IIIIII", d, e + 16)
    by_ord = {}
    for i in range(nnames):
        name_rva = struct.unpack_from("<I", d, off(names) + 4 * i)[0]
        idx = struct.unpack_from("<H", d, off(ords) + 2 * i)[0]
        n = off(name_rva)
        by_ord[base + idx] = d[n:d.index(b"\0", n)].decode()
    exports = []
    for idx in range(nfuncs):
        if struct.unpack_from("<I", d, off(funcs) + 4 * idx)[0] == 0:
            continue
        exports.append((base + idx, by_ord.get(base + idx)))
    return exports


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else r"C:\Windows\System32\winmm.dll"
    outdir = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), "..", "src")
    dll = os.path.splitext(os.path.basename(src))[0].lower()
    exports = read_exports(src)

    c = [
        f"/* Generated by tools/gen_proxy.py from {os.path.basename(src)} - do not edit. */",
        "#include <windows.h>",
        "",
        f"void *g_proxy_procs[{len(exports)}];",
        "",
    ]
    for i, (ordinal, name) in enumerate(exports):
        c.append(
            f"__attribute__((naked)) void proxy_{ordinal}(void) "
            f'{{ __asm__ volatile("jmp *g_proxy_procs+{8 * i}(%rip)"); }}'
        )
    c += ["", "static const struct { const char *name; WORD ordinal; } g_proxy_exports[] = {"]
    for ordinal, name in exports:
        c.append(f'    {{ {f"{chr(34)}{name}{chr(34)}" if name else "NULL"}, {ordinal} }},')
    c += [
        "};",
        "",
        "/* Loads the real DLL from the system directory and fills the jump table. */",
        "BOOL proxy_init(void)",
        "{",
        "    WCHAR path[MAX_PATH];",
        "    UINT n = GetSystemDirectoryW(path, MAX_PATH);",
        f'    if (n == 0 || n + 12 >= MAX_PATH) return FALSE;',
        f'    lstrcatW(path, L"\\\\{dll}.dll");',
        "    HMODULE real = LoadLibraryW(path);",
        "    if (!real) return FALSE;",
        "    for (int i = 0; i < (int)(sizeof g_proxy_exports / sizeof g_proxy_exports[0]); i++) {",
        "        const char *key = g_proxy_exports[i].name ? g_proxy_exports[i].name",
        "                                                  : (const char *)(ULONG_PTR)g_proxy_exports[i].ordinal;",
        "        g_proxy_procs[i] = (void *)GetProcAddress(real, key);",
        "    }",
        "    return TRUE;",
        "}",
        "",
    ]
    with open(os.path.join(outdir, f"{dll}_proxy.c"), "w", newline="\n") as f:
        f.write("\n".join(c))

    lines = [f"LIBRARY {dll}.dll", "EXPORTS"]
    for ordinal, name in exports:
        if name:
            lines.append(f"    {name}=proxy_{ordinal} @{ordinal}")
        else:
            lines.append(f"    proxy_{ordinal} @{ordinal} NONAME")
    with open(os.path.join(outdir, f"{dll}.def"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(exports)} exports ({sum(1 for _, n in exports if not n)} ordinal-only) -> {outdir}")


if __name__ == "__main__":
    main()
